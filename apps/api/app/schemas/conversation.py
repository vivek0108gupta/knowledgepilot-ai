import uuid
from datetime import datetime
from typing import Annotated, Any

from pydantic import AfterValidator, BaseModel, ConfigDict, Field, StringConstraints

from app.models.conversation import (
    DEFAULT_CONVERSATION_TITLE,
    MAX_TITLE_LENGTH,
    ConversationStatus,
    MessageRole,
)
from app.schemas.workspace import no_control_characters

MAX_MESSAGE_LENGTH = 8000

ConversationTitle = Annotated[
    str,
    StringConstraints(strip_whitespace=True, min_length=1, max_length=MAX_TITLE_LENGTH),
    AfterValidator(no_control_characters),
]


def not_blank(value: str) -> str:
    if not value.strip():
        raise ValueError("must not be blank")
    if "\x00" in value:
        raise ValueError("must not contain NUL characters")
    return value


# Not stripped: a message is stored as written, so code and indentation survive.
MessageContent = Annotated[
    str, StringConstraints(min_length=1, max_length=MAX_MESSAGE_LENGTH), AfterValidator(not_blank)
]


class ConversationCreate(BaseModel):
    # `extra="forbid"` rejects workspace_id, created_by, status and anything else a client
    # might try to set: those come from the URL, the token and the server.
    model_config = ConfigDict(extra="forbid")

    title: ConversationTitle = DEFAULT_CONVERSATION_TITLE


class ConversationUpdate(BaseModel):
    model_config = ConfigDict(extra="forbid")

    title: ConversationTitle


class ConversationOut(BaseModel):
    id: uuid.UUID
    workspace_id: uuid.UUID
    title: str
    status: ConversationStatus
    message_count: int
    created_at: datetime
    updated_at: datetime


class ConversationPage(BaseModel):
    """One page of the caller's own conversations, most recently active first."""

    items: list[ConversationOut]
    total: int
    limit: int
    offset: int


class MessageCreate(BaseModel):
    """A message from the signed-in user.

    There is no `role` field: this endpoint only ever creates user messages, and
    `extra="forbid"` rejects a request that tries to send a role or a sequence number.
    """

    model_config = ConfigDict(extra="forbid")

    content: MessageContent
    # Generated by the client once per message and resent on retry, so a message that is
    # submitted twice is stored once.
    client_message_id: uuid.UUID | None = None


class MessageOut(BaseModel):
    id: uuid.UUID
    conversation_id: uuid.UUID
    role: MessageRole
    content: str
    sequence_number: int
    metadata: dict[str, Any] | None = None
    created_at: datetime


class MessagePage(BaseModel):
    """Messages in ascending order. `has_more` means older messages exist before the first."""

    items: list[MessageOut]
    total: int
    has_more: bool


class MessageQuery(BaseModel):
    limit: int = Field(default=50, ge=1, le=200)
    before: int | None = Field(default=None, ge=1)
